def _single_model_route(model_key: str):
    image_bytes = _get_image_bytes()
    if not image_bytes:
        return jsonify({"error": "No image provided"}), 400

    is_valid, reason = is_crop_image(image_bytes)
    if not is_valid:
        return jsonify({"success": False, "is_crop": False, "message": reason}), 200

    if model_key not in LOADED_MODELS:
        return jsonify({"error": f"Model '{model_key}' not loaded"}), 503

    tensor = preprocess(image_bytes)
    idx, conf, probs = predict_with_model(LOADED_MODELS[model_key], tensor)

    return jsonify(build_response(idx, conf, probs)), 200


