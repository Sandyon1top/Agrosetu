LOADED_MODELS: dict[str, nn.Module] = {}

def _load_model(name: str, builder, filename: str):
    path = MODEL_PATH / filename
    if not path.exists():
        print(f"[LOAD] ⚠️  {filename} not found — skipping {name}")
        return
    try:
        model = builder() if callable(builder) else builder
        model.load_state_dict(
            torch.load(str(path), map_location=DEVICE), strict=False
        )
        model.to(DEVICE).eval()
        LOADED_MODELS[name] = model
        params = sum(p.numel() for p in model.parameters()) / 1e6
        print(f"[LOAD] ✅ {name}  ({params:.1f}M params)  from {filename}")
    except Exception as e:
        print(f"[LOAD] ❌ {name} failed: {e}")


