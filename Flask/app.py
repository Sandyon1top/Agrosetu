@app.route("/predict", methods=["POST"])
def predict_ensemble():
    image_bytes = _get_image_bytes()
    if not image_bytes:
        return jsonify({"error": "No image provided"}), 400

    is_valid, reason = is_crop_image(image_bytes)
    if not is_valid:
        return jsonify({"success": False, "is_crop": False, "message": reason}), 200

    if not LOADED_MODELS:
        return jsonify({"error": "No models loaded"}), 503

    tensor = preprocess(image_bytes)
    all_probs = []

    with torch.no_grad():
        for name, model in LOADED_MODELS.items():
            idx, conf, probs = predict_with_model(model, tensor)
            if conf >= 25.0:   # skip clearly-broken models
                all_probs.append(probs)
                print(f"  [{name}] {class_key_to_display(IDX_TO_CLASS.get(idx,'?'))} ({conf:.1f}%)")
            else:
                print(f"  [{name}] SKIPPED (conf={conf:.1f}% too low)")

    if not all_probs:
        return jsonify({"success": False, "is_crop": True,
                        "message": "All models returned low confidence. Try a clearer image."}), 200

    ensemble  = np.mean(all_probs, axis=0)
    class_idx = int(np.argmax(ensemble))
    confidence = float(ensemble[class_idx]) * 100

    return jsonify(build_response(class_idx, confidence, ensemble.tolist())), 200


