def get_groq_disease_info(disease_display_name: str, confidence: float) -> dict:
    """
    Ask Groq LLaMA-3 for detailed, structured disease advice.
    Returns a dict matching the shape Flutter expects.
    """
    healthy = "healthy" in disease_display_name.lower()

    if healthy:
        prompt = f"""The crop disease detection model identified: "{disease_display_name}" with {confidence:.1f}% confidence.
The plant appears healthy. Provide a JSON response with:
- "disease_name": friendly display name
- "description": brief description of healthy status (2-3 sentences)
- "solutions": list of 4-5 maintenance tips to keep the plant healthy
- "pesticide": "None required"
- "dosage": "N/A"
- "frequency": "N/A"
- "prevention": practical ongoing prevention advice (2-3 sentences)
- "stage": "Healthy"

Respond with ONLY valid JSON, no markdown, no extra text."""
    else:
        prompt = f"""You are an expert agronomist AI assistant. The crop disease detection model identified:
Disease: "{disease_display_name}"
Confidence: {confidence:.1f}%

Provide a detailed, actionable JSON response with these exact keys:
- "disease_name": clean display name of the disease
- "description": detailed scientific + practical description (3-4 sentences, include pathogen name if applicable)
- "solutions": list of 5-6 specific actionable steps a farmer should take RIGHT NOW, in priority order
- "pesticide": specific pesticide name(s) with active ingredient
- "dosage": exact dosage (e.g., "2.5g per litre of water")
- "frequency": application frequency (e.g., "Every 7 days for 3 weeks")
- "prevention": 3-4 sentence prevention strategy for future seasons
- "stage": disease severity/stage (e.g., "Early", "Moderate", "Advanced", "Critical")
- "organic_alternatives": list of 2-3 organic/natural treatment options
- "economic_impact": brief note on yield loss if untreated (1 sentence)
- "favorable_conditions": weather/environmental conditions that favor this disease (1-2 sentences)

Be specific, practical, and farmer-friendly. Use metric units.
Respond with ONLY valid JSON, no markdown, no extra text."""

    if GROQ_CLIENT is None:
        print("[GROQ] no API key configured — returning fallback")
        return _fallback_disease_info(disease_display_name)
    try:
        response = GROQ_CLIENT.chat.completions.create(
            model=GROQ_MODEL,
            messages=[{"role": "user", "content": prompt}],
            temperature=0.3,
            max_tokens=1024,
        )
        raw = response.choices[0].message.content.strip()
        if raw.startswith("```"):
            raw = raw.split("```")[1]
            if raw.startswith("json"):
                raw = raw[4:]
        return json.loads(raw.strip())
    except json.JSONDecodeError as e:
        print(f"[GROQ] JSON parse error: {e}")
        return _fallback_disease_info(disease_display_name)
    except Exception as e:
        print(f"[GROQ] API error ({type(e).__name__}): {e}")
        return _fallback_disease_info(disease_display_name)


