def _get_image_bytes() -> bytes | None:
    if "image" in request.files:
        f = request.files["image"]
        return f.read() if f.filename else None
    if "image_data" in request.form:
        return base64.b64decode(request.form["image_data"])
    return None


def _validate_and_preprocess(image_bytes: bytes):
    """Returns (tensor, error_response) — one of them is None."""
    is_valid, reason = is_crop_image(image_bytes)
    if not is_valid:
        return None, jsonify({"success": False, "is_crop": False, "message": reason}), 200
    tensor = preprocess(image_bytes)
    return tensor, None, None


