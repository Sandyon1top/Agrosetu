def predict_with_model(model: nn.Module, image_tensor: torch.Tensor) -> tuple[int, float, list]:
    """Returns (class_idx, confidence_pct, all_probs_list)"""
    with torch.no_grad():
        out   = model(image_tensor.to(DEVICE))
        probs = torch.softmax(out, dim=1)[0].cpu().numpy()
    idx  = int(np.argmax(probs))
    conf = float(probs[idx]) * 100
    return idx, conf, probs.tolist()


