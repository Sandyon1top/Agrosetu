def is_crop_image(image_bytes: bytes) -> tuple[bool, str]:
    try:
        pil = Image.open(io.BytesIO(image_bytes)).convert("RGB")
        arr = np.array(pil, dtype=np.float32)
        r, g, b = arr[:,:,0], arr[:,:,1], arr[:,:,2]
        green_ratio = np.sum((g > r) & (g > b)) / (arr.shape[0] * arr.shape[1])

        # Relax green check — not all diseased leaves are bright green
        if green_ratio < 0.08 and np.mean(g) < max(np.mean(r), np.mean(b)):
            return False, "This doesn't look like a plant image. Please upload a clear photo of a leaf."

        if IMAGENET_VALIDATOR is not None:
            t = VALIDATOR_TF(pil).unsqueeze(0).to(DEVICE)
            with torch.no_grad():
                probs   = torch.softmax(IMAGENET_VALIDATOR(t), dim=1)[0]
                top10   = torch.topk(probs, 10).indices.cpu().numpy().tolist()
            if not (set(top10) & PLANT_IMAGENET_IDS):
                return False, "This doesn't look like a crop or plant image. Please upload a clear photo of a plant leaf."

        return True, "ok"
    except Exception as e:
        print(f"[VALIDATOR] Error: {e}")
        return True, "ok"   # allow through if validator crashes


